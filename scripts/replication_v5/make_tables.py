# ----------------------------------------------------------------------------- helpers
def read_csv(rel):
    """Read ROOT/rel; raise with the full path if it is missing."""
    path = os.path.join(ROOT, rel)
    if not os.path.isfile(path):
        raise FileNotFoundError("missing input file: " + path)
    if rel not in INPUTS_USED:
        INPUTS_USED.append(rel)
    d = pd.read_csv(path)
    assert len(d) > 0, "empty input file: " + path
    return d


def write_table(label, sources, body):
    """Write OUT_DIR/tab_<label>.tex; refuse to overwrite."""
    path = os.path.join(OUT_DIR, "tab_" + label + ".tex")
    if os.path.exists(path):
        raise FileExistsError("refusing to overwrite existing output: " + path)
    assert re.search(r"\bnan\b|\binf\b", body.lower()) is None, label + ": NaN/inf in table body"
    head = "% generated by make_tables.py (tab:" + label + ") from:\n"
    head += "".join("%   " + s + "\n" for s in sources)
    with open(path, "w") as f:
        f.write(head + body)
    WRITTEN.append(path)
    print("wrote " + path)


def chk(x):
    x = float(x)
    assert np.isfinite(x), "non-finite value"
    return x


def sa(x, d=3):
    """Signed, whole number in math mode: $+0.012$ / $-0.012$."""
    return "$%+.*f$" % (d, chk(x))


def sb(x, d=3):
    """Signed, text style: +0.012 / $-$0.012."""
    s = "%+.*f" % (d, chk(x))
    return "$-$" + s[1:] if s[0] == "-" else s


def un(x, d=3):
    """Unsigned: 0.012."""
    return "%.*f" % (d, chk(x))


def bra(lo, hi, d=3):
    return "[" + sa(lo, d) + ", " + sa(hi, d) + "]"


def brb(lo, hi, d=3):
    return "[" + sb(lo, d) + ", " + sb(hi, d) + "]"


def pct_int(x):
    """Share in [0,1] -> integer percent, half up (0.4667 -> 47)."""
    return "%d" % int(np.floor(chk(x) * 100.0 + 0.5))


def thousands(n):
    return "{:,}".format(int(n))


def load_eval(size, region, seed, rand):
    rel = "outputs/eval_region_%s_contrastive_e_fullsrc_loro_%s_s%d%s.csv" % (
        size, region, seed, "_rand" if rand else "")
    d = read_csv(rel)
    assert set(d["unit"]) == {region}, rel
    assert d.duplicated(["mode", "target", "model"]).sum() == 0, rel + ": duplicate rows"
    return d


def eval_scores(d, target, modes):
    """mean over the given modes of score, per model (modes = folds for pooled)."""
    x = d[(d["target"] == target) & (d["mode"].isin(modes))]
    p = x.pivot(index="mode", columns="model", values="score")
    assert sorted(p.index) == sorted(modes), "modes missing for " + target
    assert {"persistence", "base", "emb", "emb_base"} <= set(p.columns)
    assert p.notna().all().all()
    return p.mean(axis=0)


def boot_lookup(d, comparison, region, name):
    x = d[(d["comparison"] == comparison) & (d["region"] == region)]
    assert len(x) == 1, "%s: expected 1 row for %s/%s, found %d" % (name, comparison, region, len(x))
    if "status" in x.columns:
        assert x["status"].iloc[0] == "ok", "%s: status %s" % (name, x["status"].iloc[0])
    assert int(x["B"].iloc[0]) == 1000, name + ": B != 1000"
    return x.iloc[0]


def ft_runs(size, region, seed, share, arm):
    """Per-draw PR-AUC difference ft_pretrained - ft_scratch from one share-grid file."""
    rel = "outputs/share_grid_fullsrc/metrics_%s_finetune_%s_s%d_f%s_%s.csv" % (size, region, seed, share, arm)
    d = read_csv(rel)
    d = d[d["model"] != "persistence"]
    assert set(d["model"]) == {"ft_pretrained", "ft_scratch"}, rel
    assert np.allclose(d["share"].astype(float), float(share)), rel
    p = d.pivot(index="draw", columns="model", values="pr")
    assert list(p.index) == DRAWS, rel + ": draws " + str(list(p.index))
    assert p.notna().all().all(), rel
    return (p["ft_pretrained"] - p["ft_scratch"]).values, d


