"""make_tables.py -- LaTeX tables for the replication package (manuscript of Nov 2, 2026).

One block per table, in manuscript order. Each block reads named result files under ROOT,
asserts their shape and keys, computes the reported values the way the manuscript does, and
writes OUT_DIR/tab_<label>.tex, where <label> is the manuscript \\label without "tab:".
Each output holds the tabular (with its \\resizebox wrapper where the manuscript has one) and
the table note, so it can be \\input in place of the inline tabular + note. The surrounding
table float, \\caption and \\label stay in main.tex.

Environment
  TABLES_ROOT  conflict_forecast directory (default: the Roar path below)
  TABLES_OUT   output directory (default: {TABLES_ROOT}/figures_tables/tables_v5)
  UKRAINE_FULL=1 (or command-line flag --ukraine-full): add the all-parameters fine-tuning
               block to tab_ukraine_ft.tex. Requires
               outputs/country_window_incidence_M_fullsrc_full.csv and
               outputs/country_slice_incidence_M_fullsrc_full.csv; stops with an error if absent.

Not generated (no result file behind them): tab:design (Table 1, design constants) and
tab:brazil_vocab (Table 9, ICD-10 mapping). Cut by the author: transfer matrix (old Table 3),
tab:finetune_civilian (old Table 14), AR-objective table (old Table 16).

Rounding: every number is printed with Python "%+.3f" / "%.3f" (or the stated number of
decimals) applied to the unrounded value; the sign of a value that rounds to zero is kept
("-0.000"), as elsewhere in the manuscript. Python 3.9+, pandas and numpy only.
"""
